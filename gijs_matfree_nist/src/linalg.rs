//! Linear algebra helpers: kernel basis for shortening.

use crate::gf::Gf;

/// Row-reduced echelon form + kernel basis.
/// Input: rows (m x k). Returns (rank, basis) where basis is (k-rank) x k,
/// rows form a basis for ker(rows as a linear map F_q^k -> F_q^m).
pub fn kernel_basis(gf: &Gf, rows: &[Vec<u16>]) -> (usize, Vec<Vec<u16>>) {
    let m = rows.len();
    if m == 0 {
        return (0, Vec::new());
    }
    let k = rows[0].len();
    let mut a: Vec<Vec<u16>> = rows.to_vec();
    let mut pivots: Vec<Option<usize>> = vec![None; k]; // col -> row
    let mut row = 0usize;
    for col in 0..k {
        // find pivot
        let mut p: Option<usize> = None;
        for r in row..m {
            if a[r][col] != 0 {
                p = Some(r);
                break;
            }
        }
        if let Some(pr) = p {
            a.swap(row, pr);
            let inv = gf.inv(a[row][col]);
            if inv != 1 {
                for c in col..k {
                    a[row][c] = gf.mul(a[row][c], inv);
                }
            }
            // eliminate in all other rows (Gauss-Jordan for kernel)
            for r in 0..m {
                if r != row && a[r][col] != 0 {
                    let f = a[r][col];
                    for c in col..k {
                        let sub = gf.mul(f, a[row][c]);
                        a[r][c] ^= sub;
                    }
                }
            }
            pivots[col] = Some(row);
            row += 1;
            if row == m {
                // remaining columns are free, but continue to mark pivots
                // (no more rows, so done)
            }
        }
    }
    let rank = row;
    // free columns -> kernel basis vectors
    let mut basis = Vec::new();
    for fc in 0..k {
        if pivots[fc].is_none() {
            // basis vector: 1 at fc, -a[r][fc] at pivot col of row r
            let mut v = vec![0u16; k];
            v[fc] = 1;
            for c in 0..k {
                if let Some(r) = pivots[c] {
                    // a[r][fc] is the coefficient; v[c] = -a[r][fc] = a[r][fc] (char 2)
                    v[c] = a[r][fc];
                }
            }
            basis.push(v);
        }
    }
    (rank, basis)
}

/// Shorten the code generated by `cols` (k x N) at positions `hit`.
/// Returns (shortened_cols as k' x n' vec, kept_original_indices).
/// The shortened code is { (x.G)_j : j not in hit, x in ker(G_hit^T) }.
pub fn shorten(
    gf: &Gf,
    cols: &[Vec<u16>],
    hit: &[usize],
) -> (Vec<Vec<u16>>, Vec<usize>) {
    let n = cols.len();
    let k = cols[0].len();
    let hit_set: std::collections::HashSet<usize> = hit.iter().cloned().collect();
    let kept: Vec<usize> = (0..n).filter(|j| !hit_set.contains(j)).collect();

    // A[i][l] = cols[hit[i]][l]: h x k matrix; kernel gives shortening basis
    let a: Vec<Vec<u16>> = hit.iter().map(|&j| cols[j].clone()).collect();
    let (_rank, basis) = kernel_basis(gf, &a);
    let kp = basis.len();
    // shortened column j = basis * cols[kept[j]] (matrix-vector)
    let mut out = Vec::with_capacity(kept.len());
    for &j in kept.iter() {
        let mut col = vec![0u16; kp];
        for (i, b) in basis.iter().enumerate() {
            let mut acc = 0u16;
            for (l, &bl) in b.iter().enumerate() {
                acc ^= gf.mul(bl, cols[j][l]);
            }
            col[i] = acc;
        }
        out.push(col);
    }
    (out, kept)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::gf::Gf;
    use crate::rng::Rng;

    #[test]
    fn kernel_dim() {
        let gf = Gf::new(6);
        let mut rng = Rng::new(123);
        // random 5x8 matrix, expect rank 5, kernel dim 3
        let rows: Vec<Vec<u16>> = (0..5)
            .map(|_| (0..8).map(|_| rng.below(64) as u16).collect())
            .collect();
        let (rank, basis) = kernel_basis(&gf, &rows);
        assert_eq!(rank, 5);
        assert_eq!(basis.len(), 3);
        // verify: each basis vector in kernel
        for b in &basis {
            for r in &rows {
                let mut acc = 0u16;
                for (x, y) in b.iter().zip(r.iter()) {
                    acc ^= gf.mul(*x, *y);
                }
                assert_eq!(acc, 0);
            }
        }
    }
}
